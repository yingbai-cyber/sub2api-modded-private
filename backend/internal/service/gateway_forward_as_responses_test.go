// ---------- 空流 sentinel 行为 ----------

func TestHandleResponsesBufferedStreamingResponse_EmptyStreamReturnsSentinel(t *testing.T) {
	t.Parallel()
	gin.SetMode(gin.TestMode)

	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)

	// 上游返 200 + SSE headers 但流里没有任何 message_start
	// 只含 ping / comment，不构成有效响应
	resp := &http.Response{
		Header: http.Header{"x-request-id": []string{"rid_empty_buf"}},
		Body: io.NopCloser(strings.NewReader(strings.Join([]string{
			`event: ping`,
			`data: {"type":"ping"}`,
			``,
		}, "\n"))),
	}

	svc := &GatewayService{}
	result, err := svc.handleResponsesBufferedStreamingResponse(resp, c, "claude-sonnet-4.5", "claude-sonnet-4.5", nil, time.Now())
	require.Nil(t, result)
	require.ErrorIs(t, err, ErrUpstreamEmptyStream, "buffered 路径空流必须返 sentinel")
	// 关键不变量：未向客户端写任何错误响应，交给外层 retry
	require.Equal(t, 200, rec.Code, "handler 不应写入 HTTP 状态（rec 默认 200）")
	require.Empty(t, rec.Body.String(), "空流场景下 handler 不应写 body")
}

func TestHandleResponsesStreamingResponse_EmptyStreamReturnsSentinelAndNoHeadersWritten(t *testing.T) {
	t.Parallel()
	gin.SetMode(gin.TestMode)

	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)

	// 上游 200 但流内只有 ping，没有 message_start/content_block_* 等业务事件
	resp := &http.Response{
		Header: http.Header{"x-request-id": []string{"rid_empty_stream"}},
		Body: io.NopCloser(strings.NewReader(strings.Join([]string{
			`event: ping`,
			`data: {"type":"ping"}`,
			``,
		}, "\n"))),
	}

	svc := &GatewayService{}
	result, err := svc.handleResponsesStreamingResponse(resp, c, "claude-sonnet-4.5", "claude-sonnet-4.5", nil, time.Now())
	require.Nil(t, result)
	require.True(t, errors.Is(err, ErrUpstreamEmptyStream), "streaming 路径空流必须返 sentinel")
	// 推迟 WriteHeader 后的关键保障：body 从未写入，retry 对客户端透明
	require.Empty(t, rec.Body.String(), "空流场景下 handler 不应写 body（headers 从未提交）")
	require.Empty(t, rec.Header().Get("Content-Type"), "headers 应未被写入")
}

